-- People and gear belong to projects; the cruise holds only the sailing.
--   * cruise_people becomes crew only. The MFP science party (PI / chief scientist per
--     application) moves to project_people, person links intact.
--   * cruise_equipment becomes bid-confirmed gear only. The MFP SME lines were requests, so
--     they move to project_gear (their ship/pool/science-party origin kept in notes).
--   * timeline_entries gains project_person_id: a person on a scheduled project is busy for
--     the cruise's window (lib/timeline-service.ts syncs these like seats).
--   * cruises.summary goes: every one was a copy of a project's summary.

-- ── 1. entries can point at a project person ────────────────────────────────
alter table timeline_entries add column if not exists project_person_id uuid references project_people(id) on delete cascade;
create unique index if not exists timeline_entries_project_person_key on timeline_entries (project_person_id) where project_person_id is not null and deleted_at is null;
create index if not exists timeline_entries_project_person_idx on timeline_entries (project_person_id) where deleted_at is null;

-- ── 2. MFP seats → project people ───────────────────────────────────────────
-- A seat came from the application whose Users list names that MFP person in that role.
insert into project_people (project_id, role_id, person_id, name, notes, created_at)
select p.id, s.role_id, s.person_id, s.name, s.notes, s.created_at
from cruise_people s
join projects p on p.cruise_id = s.cruise_id and p.source = 'unols_mfp'
join cruise_roles r on r.id = s.role_id
where s.source = 'unols_mfp' and s.deleted_at is null
  and exists (select 1 from jsonb_array_elements(p.raw->'Users') u
              where u->>'Person_id' = s.external_id
                and r.slug = case u->>'Role' when 'PI' then 'pi' when 'CS' then 'chief_scientist' else 'other' end)
  and not exists (select 1 from project_people pp where pp.project_id = p.id and pp.person_id = s.person_id and pp.role_id = s.role_id);

-- seats that moved: soft-delete them and their entries
update cruise_people s set deleted_at = now()
where s.source = 'unols_mfp' and s.deleted_at is null
  and exists (select 1 from project_people pp join projects p on p.id = pp.project_id
              where p.cruise_id = s.cruise_id and pp.person_id = s.person_id and pp.role_id = s.role_id);
update timeline_entries e set deleted_at = now()
from cruise_people s where e.seat_id = s.id and s.deleted_at is not null and e.deleted_at is null;

-- one entry per project person on a live, scheduled cruise (window = the vessel's entry)
insert into timeline_entries (person_id, start_at, end_at, all_day, tz, cruise_id, project_person_id, source, visibility)
select pp.person_id, e.start_at, e.end_at, e.all_day, e.tz, c.id, pp.id, c.source, 'operators'
from project_people pp
join projects p on p.id = pp.project_id and p.cruise_id is not null
join cruises c on c.id = p.cruise_id and c.cancelled_at is null
join timeline_entries e on e.cruise_id = c.id and e.vessel_id is not null and e.deleted_at is null
where pp.person_id is not null
  and not exists (select 1 from timeline_entries x where x.project_person_id = pp.id and x.deleted_at is null);

-- ── 3. MFP gear lines → project gear ────────────────────────────────────────
insert into project_gear (project_id, label, equipment_type_id, quantity, notes, created_at)
select p.id, ce.label, ce.equipment_type_id, ce.quantity,
       case ce.provided_by when 'ship' then 'Ship fitted' when 'pool' then 'Pooled / portable' when 'science_party' then 'Science party brings' end,
       ce.created_at
from cruise_equipment ce
join projects p on p.cruise_id = ce.cruise_id and p.source = 'unols_mfp'
where ce.source = 'unols_mfp_sme'
  and (p.raw->'sme'->'equipment'->'ship_fitted' ? ce.label
       or p.raw->'sme'->'equipment'->'pooled_portable' ? ce.label
       or (ce.label = 'Science-provided vans' and coalesce((p.raw->'sme'->'equipment'->>'vans')::int, 0) > 0))
  and not exists (select 1 from project_gear g where g.project_id = p.id and g.label = ce.label);
-- the SME lines were generated by scripts/backfill_cruise_equipment.mjs; they can be regenerated
delete from cruise_equipment where source = 'unols_mfp_sme';

-- ── 4. the cruise has no summary of its own ─────────────────────────────────
alter table cruises drop column if exists summary;
