"""Generate the vessel_organizations backfill migration from the reviewed
scripts/org_mapping.csv and the curated list in build_org_mapping.py.

Usage: python3 scripts/build_org_backfill.py <vessels.json> <out.sql>
vessels.json: [{id, status, country, affiliation, operator_name, owner, linked_org}] for ALL vessels.
"""
import csv, json, sys
from collections import Counter, defaultdict
import importlib.util

spec = importlib.util.spec_from_file_location('m', 'scripts/build_org_mapping.py')
m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)

vessels = json.load(open(sys.argv[1]))
out_path = sys.argv[2]

# Organizations: curated list first, then names the reviewed mapping kept as-is.
orgs = {}
for name, short, kind, country, parent, aliases in m.ORGS:
    orgs[name] = dict(name=name, short=short, kind=kind, country=country, parent=parent)
mapping = defaultdict(list)  # raw -> [organization]
for r in csv.DictReader(open('scripts/org_mapping.csv')):
    if r['organization']:
        mapping[r['raw_name']].append(r['organization'])
        orgs.setdefault(r['organization'], dict(name=r['organization'], short=r['short_name'] or None,
                                                kind=r['kind'], country=r['country'] or None, parent=r['parent'] or None))
alias_index = {}
for o in orgs.values():
    for a in (o['name'], o['short'] or ''):
        if a: alias_index.setdefault(m.key(a), o['name'])
for name, short, kind, country, parent, aliases in m.ORGS:
    for a in aliases: alias_index.setdefault(m.key(a), name)

def resolve(raw, country):
    if raw in m.PEOPLE or raw in m.PRIVATE: return []
    if (raw, country) in m.BY_COUNTRY: return [m.BY_COUNTRY[(raw, country)]]
    if raw in m.MULTI: return m.MULTI[raw]
    targets = mapping.get(raw)
    if targets:
        # Split-meaning names (Marine Institute) carry several rows; the non-country one is the default.
        return [t for t in targets if t not in {v for (r, _), v in m.BY_COUNTRY.items() if r == raw}][:1] or targets[:1]
    hit = alias_index.get(m.key(raw))
    if hit: return [hit]
    name = m.tidy(raw)  # inactive/retired vessels whose names weren't in the review file
    orgs.setdefault(name, dict(name=name, short=None, kind=m.guess_kind(name), country=country, parent=None))
    alias_index[m.key(raw)] = name
    new_unreviewed.append((raw, name))
    return [name]

new_unreviewed = []
links, people = set(), set()
ROLE = {'affiliation': 'affiliation', 'operator_name': 'operator', 'owner': 'owner'}
PERSON_ROLE = {'owner': 'Owner', 'operator_name': 'Operator'}
for v in vessels:
    for field, role in ROLE.items():
        raw = (v[field] or '').strip()
        if not raw: continue
        if raw in m.PEOPLE:
            people.add((v['id'], raw.split(',')[0].replace('Captain ', '').strip(), PERSON_ROLE[field]))
            continue
        targets = resolve(raw, v['country'])
        if role == 'owner' and len(targets) > 1:
            # Joint owners in one field; the schema allows one owning organization at a time.
            print(f"  vessel {v['id']}: joint owners {targets}, keeping {targets[0]}")
            targets = targets[:1]
        for org in targets:
            links.add((v['id'], org, role))
    if v['linked_org']:
        links.add((v['id'], v['linked_org'], 'operator'))

owners = Counter(vid for vid, _, role in links if role == 'owner')
assert all(c == 1 for c in owners.values()), [vid for vid, c in owners.items() if c > 1]

# Aliases: every spelling that differs from the organization's own name key.
name_keys = {m.key(n) for n in orgs}
aliases = {}
for raw, targets in mapping.items():
    if len(set(targets)) == 1 and raw not in m.MULTI and m.key(raw) not in name_keys:
        aliases.setdefault(m.key(raw), (raw, targets[0]))
for name, short, kind, country, parent, al in m.ORGS:
    for a in al:
        if m.key(a) not in name_keys and (not short or m.key(a) != m.key(short)):
            aliases.setdefault(m.key(a), (a, name))
for raw, name in new_unreviewed:
    if m.key(raw) not in name_keys: aliases.setdefault(m.key(raw), (raw, name))

q = lambda s: 'null' if s is None or s == '' else "'" + str(s).replace("'", "''") + "'"
used = {o for _, o, _ in links} | {o['parent'] for o in orgs.values() if o['parent']}
for _ in range(3):  # parents of parents
    used |= {orgs[o]['parent'] for o in list(used) if o in orgs and orgs[o]['parent']}
existing16 = set(json.load(open(sys.argv[1].replace('.json', '_orgs.json'))))
org_rows = [orgs[n] for n in sorted(used | (existing16 & set(orgs)))]

sql = ["-- Generated by scripts/build_org_backfill.py from scripts/org_mapping.csv. Data only.",
       "create temp table _org(name text, short_name text, kind text, country text, parent text) on commit drop;",
       "insert into _org values"]
sql.append(',\n'.join(f"  ({q(o['name'])}, {q(o['short'])}, {q(o['kind'])}, {q(o['country'])}, {q(o['parent'])})" for o in org_rows) + ';')
sql += ["""
insert into public.organizations (name, short_name, kind, country, reviewed_at)
select name, short_name, kind, country, now() from _org
on conflict ((lower(name))) do update
  set short_name = coalesce(public.organizations.short_name, excluded.short_name),
      kind = excluded.kind,
      country = coalesce(public.organizations.country, excluded.country);

update public.organizations o set parent_id = p.id
from _org t join public.organizations p on lower(p.name) = lower(t.parent)
where lower(o.name) = lower(t.name) and t.parent is not null;
""", "create temp table _alias(alias text, org text) on commit drop;", "insert into _alias values"]
sql.append(',\n'.join(f"  ({q(a)}, {q(o)})" for a, o in sorted(aliases.values())) + ';')
sql += ["""
insert into public.organization_aliases (organization_id, alias)
select o.id, a.alias from _alias a join public.organizations o on lower(o.name) = lower(a.org)
on conflict (alias_key) do nothing;
""", "create temp table _link(vessel_id int, org text, role text) on commit drop;", "insert into _link values"]
sql.append(',\n'.join(f"  ({vid}, {q(o)}, {q(r)})" for vid, o, r in sorted(links)) + ';')
sql += ["""
insert into public.vessel_organizations (vessel_id, organization_id, role)
select l.vessel_id, o.id, l.role from _link l join public.organizations o on lower(o.name) = lower(l.org);
"""]
if people:
    sql += ["create temp table _person(vessel_id int, name text, role text) on commit drop;", "insert into _person values"]
    sql.append(',\n'.join(f"  ({vid}, {q(n)}, {q(r)})" for vid, n, r in sorted(people)) + ';')
    sql += ["""
insert into public.people (name, source)
select distinct p.name, 'vesselconnect' from _person p
where not exists (select from public.people x where lower(x.name) = lower(p.name) and x.source = 'vesselconnect');

insert into public.vessel_people (vessel_id, person_id, role)
select p.vessel_id, x.id, p.role from _person p
join public.people x on lower(x.name) = lower(p.name) and x.source = 'vesselconnect';
"""]
open(out_path, 'w').write('\n'.join(sql) + '\n')
print(f"organizations: {len(org_rows)}  aliases: {len(aliases)}  vessel links: {len(links)} "
      f"({dict(Counter(r for _, _, r in links))})  people links: {len(people)}  vessels linked: {len({v for v, _, _ in links})}")
print('New orgs from inactive/retired vessels (not in review file):')
for raw, name in new_unreviewed: print('  ', repr(raw), '->', name)
